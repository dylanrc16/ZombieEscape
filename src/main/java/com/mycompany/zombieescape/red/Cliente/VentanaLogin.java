    private void btnEntrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEntrarActionPerformed
        String nombre = txtNombre.getText().trim();
        String ip = txtIp.getText().trim();

        if (nombre.isEmpty()) {
            lblError.setText("Escriba un nombre.");
            return;
        }
        if (nombre.length() > MAX_NOMBRE) {
            lblError.setText("El nombre puede tener máximo " + MAX_NOMBRE + " caracteres.");
            return;
        }
        if (ip.isEmpty()) {
            lblError.setText("Escriba la IP del servidor.");
            return;
        }

        lblError.setText(" ");
        String rol = rbSniper.isSelected() ? "SNIPER" : "SUPERVIVIENTE";
        iniciarJuego(nombre, ip, rol);
        
        try {
            Mensaje msg = new Mensaje("MENSAJE", 2);
            msg.parametros[0] = this.cliente.nombre; 
            msg.parametros[1] = txtNombre.getText(); 
            cliente.escritorDeObjetos.writeObject(msg);
        } catch (IOException ex) {
            System.getLogger(VentanaLogin.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }//GEN-LAST:event_btnEntrarActionPerformed

